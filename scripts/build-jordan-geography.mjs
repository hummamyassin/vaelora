/**
 * Generates src/data/jordan-geography.ts from geoBoundaries open data:
 *
 *   node scripts/build-jordan-geography.mjs <adm0.geojson> <adm1.geojson>
 *
 * ADM0: geoBoundaries gbOpen JOR ADM0 (CC BY 4.0), build 9469f09.
 * ADM1: geoBoundaries gbOpen JOR ADM1 simplified (CC BY 2.5), build 9469f09.
 * The country ring is simplified to about 60 m, governorates to about 300 m:
 * enough for coverage and labels, small enough for the client bundle.
 */
import { readFileSync, writeFileSync } from "node:fs";

const [adm0, adm1] = process.argv.slice(2).map((f) => JSON.parse(readFileSync(f, "utf8")));

/** Douglas-Peucker on [lon, lat] pairs, tolerance in degrees. */
function simplify(points, tolerance) {
  if (points.length < 4) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [x1, y1] = points[a], [x2, y2] = points[b];
    let max = 0, at = -1;
    for (let i = a + 1; i < b; i++) {
      const [x, y] = points[i];
      const dx = x2 - x1, dy = y2 - y1;
      const t = Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy || 1)));
      const d = Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy));
      if (d > max) { max = d; at = i; }
    }
    if (max > tolerance) { keep[at] = 1; stack.push([a, at], [at, b]); }
  }
  return points.filter((_, i) => keep[i]);
}
const round = (ring) => ring.map(([x, y]) => [+x.toFixed(4), +y.toFixed(4)]);
const outer = (geometry) =>
  geometry.type === "Polygon"
    ? geometry.coordinates[0]
    : geometry.coordinates.reduce((a, p) => (p[0].length > a.length ? p[0] : a), []);

// Arabic names are the official governorate names; geoBoundaries carries English only.
const names = {
  Amman: ["amman", "Amman", "عمّان"],
  Irbid: ["irbid", "Irbid", "إربد"],
  Zarqa: ["zarqa", "Zarqa", "الزرقاء"],
  Balqa: ["balqa", "Balqa", "البلقاء"],
  Madaba: ["madaba", "Madaba", "مادبا"],
  Jerash: ["jerash", "Jerash", "جرش"],
  Ajloun: ["ajloun", "Ajloun", "عجلون"],
  Mafraq: ["mafraq", "Mafraq", "المفرق"],
  Karak: ["karak", "Karak", "الكرك"],
  Tafilah: ["tafilah", "Tafilah", "الطفيلة"],
  "Ma'an": ["maan", "Ma'an", "معان"],
  Aqaba: ["aqaba", "Aqaba", "العقبة"],
};

const country = round(simplify(outer(adm0.features[0].geometry), 0.0006));
const governorates = adm1.features
  .map((f) => {
    const [id, en, ar] = names[f.properties.shapeName];
    return { id, en, ar, ring: round(simplify(outer(f.geometry), 0.003)) };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

writeFileSync(
  "src/data/jordan-geography.ts",
  `/* Generated by scripts/build-jordan-geography.mjs. Do not edit by hand.
 * Boundaries: geoBoundaries (www.geoboundaries.org), gbOpen JOR ADM0 (CC BY 4.0)
 * and ADM1 (CC BY 2.5), build 9469f09, simplified. Coverage boundaries for the
 * product, not legal or surveyed borders. Rings are [longitude, latitude]. */
export type Ring = readonly (readonly [number, number])[];
export const jordanRing: Ring = ${JSON.stringify(country)};
export const governorateRings: readonly { id: string; en: string; ar: string; ring: Ring }[] = ${JSON.stringify(governorates)};
`,
);
console.log(`Jordan ring ${country.length} points; ${governorates.length} governorates, ${governorates.reduce((n, g) => n + g.ring.length, 0)} points`);
